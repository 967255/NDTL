"""CLI options shared by both classification benchmarks."""

from pathlib import Path


def add_shared_arguments(parser):
    parser.add_argument("--out-root", type=Path, default=None)
    parser.add_argument("--smoke-test", action="store_true")
    parser.add_argument("--merge-only", action="store_true")
    parser.add_argument("--allow-partial", action="store_true")
    parser.add_argument("--limit-systems", type=int, default=None)
    parser.add_argument("--limit-pairs", type=int, default=None)
    parser.add_argument("--pair-start", type=int, default=None)
    parser.add_argument("--pair-end", type=int, default=None)
    parser.add_argument("--pair-shard-index", type=int, default=None)
    parser.add_argument("--pair-shard-count", type=int, default=None)
    parser.add_argument("--alphas", type=str, default=None)
    parser.add_argument("--device", type=str, default=None)
    parser.add_argument("--seed", type=int, default=20260603)
    parser.add_argument("--resume", dest="resume", action="store_true", default=True)
    parser.add_argument("--no-resume", dest="resume", action="store_false")
    parser.add_argument("--lyap-h", type=float, default=0.01)
    parser.add_argument("--burn-steps", type=int, default=1000)
    parser.add_argument("--lyap-steps", type=int, default=5000)
    parser.add_argument("--max-abs", type=float, default=100000.0)
    parser.add_argument("--grid-shape", type=str, default="48,48,48")
    parser.add_argument("--cae-depth", type=int, default=64)
    parser.add_argument("--cae-batch-size", type=int, default=12)
    parser.add_argument("--cae-max-batches", type=int, default=5000)
    parser.add_argument("--cae-lr", type=float, default=0.001)
    parser.add_argument("--cae-turb-scale", type=float, default=0.1)
    parser.add_argument("--cae-reduce-factor", type=float, default=0.8)
    parser.add_argument("--cae-reduce-patience", type=int, default=100)
    parser.add_argument("--cae-early-lr", type=float, default=0.0001)
    parser.add_argument("--cae-log-every", type=int, default=500)
    parser.add_argument("--transfer-max-iters", type=int, default=10000)
    parser.add_argument("--transfer-lr", type=float, default=0.1)
    parser.add_argument("--transfer-reduce-factor", type=float, default=0.5)
    parser.add_argument("--transfer-reduce-patience", type=int, default=500)
    parser.add_argument("--transfer-early-lr", type=float, default=1e-06)
    parser.add_argument("--transfer-log-every", type=int, default=1000)
